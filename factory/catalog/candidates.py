def markdown(out):
    lines = ["# 场景站点候选清单", "",
             "由 `candidates.py` 生成。A 级为核心主流站，最高保真、优先建设；B 级为补充站。已有站点来自 CUA-Gym-Hub 并已通过认证或待修。", ""]
    for scenario, data in out.items():
        new = data["new"]
        lines += [f"## {scenario}（已有 {len(data['existing'])} + 新建 {len(new)} = {len(data['existing']) + len(new)}）", "",
                  "已有：" + "、".join(data["existing"]), "",
                  "| 级别 | 站点 | 域名 | 核心业务操作 |", "|---|---|---|---|"]
        for item in sorted(new, key=lambda x: (x["tier"], x["brand"])):
            lines.append(f"| {item['tier']} | {item['brand']} | {item['origin'].removeprefix('https://')} | {item['workflows']} |")
        lines.append("")
    return "\n".join(lines)


def main():
    catalog = json.loads((HERE / "sites.json").read_text())
    existing = {}
    for name, site in catalog["sites"].items():
        if site["role"] == "scenario" and site["locale"] == "en" and site["status"] != "needs_sync":
            existing.setdefault(site["scenario"], []).append(site["brand"])
    out, total_new = {}, 0
    for scenario, items in CANDIDATES.items():
        have = existing.get(scenario, [])
        new = [{"brand": b, "origin": f"https://{o}", "workflows": w, "tier": "A" if b in TIER_A else "B",
                "status": "to_build"} for b, o, w in items]
        out[scenario] = {"existing": have, "new": new}
        total_new += len(new)
        print(f"{scenario}: {len(have)} existing + {len(new)} new = {len(have) + len(new)}")
    (HERE / "candidates.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n")
    (HERE / "candidates.md").write_text(markdown(out))
    tier_a = sum(item["tier"] == "A" for data in out.values() for item in data["new"])
    print(f"tier A (mainstream, build first): {tier_a}")
    print(f"total new mocks: {total_new}")


if __name__ == "__main__":
    main()
